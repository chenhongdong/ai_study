# 元祖：一旦定义完成，不可修改——和列表最大的区别
# 1. 特点：
  # 可以存不同类型的元素
  # 可以重复、有序、不可以修改（支持索引访问、切片操作）

t1 = (20, 11, 20, 123, 22, 4.5, 'Ma', 102, 22, 20, 1)

print(t1[1])
print(t1[-2])
print(t1[0:5:1])
print(type(t1))


# 2. 元祖的两个查询方法
# count() 查询元素在元祖中出现的个数
print(t1.count(20))

# index() 查询元素在元祖中第一次出现的索引
print(t1.index(22))

# 3. 注意事项，单1元素的元祖后面要加个逗号
t3 = (100,)
print(type(t3))